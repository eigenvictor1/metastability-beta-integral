"""Single source of truth for the couplings of the theory.

Every module that needs a coupling's name, role, label, perturbativity limit or
convention imports it from here. The SM couplings are fixed below; the Yukawas
of the new fields are generated by Model and described by ``new_yukawa()``.

Order of the coupling vector (BetaSystem.couplings, running state):
    g1, g2, g3, yt, <new Yukawas in Model order>, [yS], lam, [lamS, kap]
(yS, lamS, kap: the scalar singlet S, when the model has one)
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np

PERT_GAUGE_YUKAWA = float(np.sqrt(4 * np.pi))   # |g|, |y| above this: non-perturbative
PERT_QUARTIC = float(4 * np.pi)                 # |λ| above this: non-perturbative


@dataclass(frozen=True)
class Coupling:
    """Everything the code needs to know about one coupling (see the field comments)."""
    name: str                 # internal name, used everywhere (JSON, CSV, BetaSystem)
    kind: str                 # "gauge" | "yukawa" | "quartic"
    sm: bool                  # part of the SM (runs below the threshold)
    latex: str                # label for plots / LaTeX export (math mode, no $)
    pyrate: str               # name used in PyR@TE model files ("" = assigned by the bridge)
    limit: float              # perturbativity limit on |value|
    convention: str = ""

    @property
    def symbol(self) -> str:
        """Name for sympy symbols / LaTeX export."""
        return "lambda" if self.name == "lam" else self.name


# --------------------------------------------------------------------------
# SM couplings
# --------------------------------------------------------------------------

G1 = Coupling("g1", "gauge", True, r"g_1", "g1", PERT_GAUGE_YUKAWA,
              "U(1)_Y gauge coupling g', SM normalisation (no GUT factor sqrt(5/3)); Q = T3 + Y")
G2 = Coupling("g2", "gauge", True, r"g_2", "g2", PERT_GAUGE_YUKAWA, "SU(2)_L gauge coupling")
G3 = Coupling("g3", "gauge", True, r"g_3", "g3", PERT_GAUGE_YUKAWA, "SU(3)_c gauge coupling")
YT = Coupling("yt", "yukawa", True, r"y_t", "yt", PERT_GAUGE_YUKAWA,
              "-L ⊃ y_t ε_ij Q3^i u^c_3 H^j + h.c. (other SM Yukawas neglected)")
LAM = Coupling("lam", "quartic", True, r"\lambda", "lam", PERT_QUARTIC,
               "V ⊃ λ (H†H)², i.e. m_h² = 2λ v² (Buttazzo et al. convention)")

SM = (G1, G2, G3, YT, LAM)

# scalar singlet S (complex, global U(1)), when the model has one: it gives the new fermions
# their mass, M = y_S v_S/√2 with ⟨S⟩ = v_S/√2
YS = Coupling("yS", "yukawa", False, r"y_S", "yS", PERT_GAUGE_YUKAWA,
              "-L ⊃ ½ y_S S ψ M0 ψ + h.c., M0 the gauge-invariant mass matrix of the new fields "
              "(Dirac pairs and Majorana fields, unit masses)")
LAMS = Coupling("lamS", "quartic", False, r"\lambda_S", "lamS", PERT_QUARTIC, "V ⊃ λ_S |S|⁴")
KAP = Coupling("kap", "quartic", False, r"\kappa", "kap", PERT_QUARTIC, "V ⊃ κ (H†H)|S|²")
SINGLET = (YS, LAMS, KAP)
SINGLET_NAMES = tuple(c.name for c in SINGLET)
SM_NAMES = tuple(c.name for c in SM)
GAUGE = tuple(c.name for c in SM if c.kind == "gauge")       # ("g1", "g2", "g3")
TOP_YUKAWA = YT.name                                          # "yt"
QUARTIC = LAM.name                                            # "lam"
_SM_BY_NAME = {c.name: c for c in SM}
_SINGLET_BY_NAME = {c.name: c for c in SINGLET}

YUKAWA_CONVENTION = ("-L ⊃ y C ψ1 ψ2 Φ + h.c., Φ = H or H^*, C the gauge-invariant tensor "
                     "normalised to max|entry| = 1 per gauge factor")
BETA_CONVENTION = "dx/dln(mu) = sum_L beta^(L)/(16 pi^2)^L"


# --------------------------------------------------------------------------
# New Yukawas
# --------------------------------------------------------------------------

def new_yukawa_name(f1: str, f2: str, conj_higgs: bool) -> str:
    """Name of the Yukawa of ψ1 ψ2 H (or H^* with conj_higgs): y<f1><f2>[c], without underscores.

    f1, f2 are component names; their copy suffix loses its underscore too (N_1 -> N1),
    e.g. N L_3 H -> yNL3, L4c N H^* -> yL4cNc. Model checks that the names are unique.
    """
    return "y" + f1.replace("_", "") + f2.replace("_", "") + ("c" if conj_higgs else "")


def is_new_yukawa(name: str) -> bool:
    """True for a name of the new-Yukawa form 'y<...>' (not an SM coupling)."""
    return (name.startswith("y") and len(name) > 2 and name not in _SM_BY_NAME
            and name not in _SINGLET_BY_NAME)


def new_yukawa(name: str) -> Coupling:
    """Coupling record of a new Yukawa from its name, e.g. yL4N -> label y_{L4N}."""
    return Coupling(name, "yukawa", False, rf"y_{{\mathrm{{{name[1:]}}}}}", "", PERT_GAUGE_YUKAWA,
                    YUKAWA_CONVENTION)


# --------------------------------------------------------------------------
# Lookup
# --------------------------------------------------------------------------

def get(name: str) -> Coupling:
    """The Coupling with this name (SM, or a new Yukawa 'y<...>')."""
    if name in _SM_BY_NAME:
        return _SM_BY_NAME[name]
    if name in _SINGLET_BY_NAME:
        return _SINGLET_BY_NAME[name]
    if is_new_yukawa(name):
        return new_yukawa(name)
    raise KeyError(f"unknown coupling {name!r}")


def ordered(yukawa_names, quartics=()) -> list[str]:
    """Full coupling order for a model: gauge, Yukawas (y_t first), λ, other quartics."""
    return [*GAUGE, *yukawa_names, QUARTIC, *quartics]


def limits(names) -> np.ndarray:
    """Perturbativity limits of the given couplings, as an array in the same order."""
    return np.array([get(n).limit for n in names])


def latex(name: str) -> str:
    """Plot label ($...$) of a coupling; unknown names are returned unchanged."""
    try:
        return f"${get(name).latex}$"
    except KeyError:
        return name


def conventions() -> dict[str, str]:
    """Written to model.json."""
    out = {c.name: c.convention for c in (*SM, *SINGLET)}
    out["new Yukawas"] = YUKAWA_CONVENTION
    out["beta functions"] = BETA_CONVENTION
    return out
